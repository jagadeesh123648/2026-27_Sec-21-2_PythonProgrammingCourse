
# Program to find the largest and smallest element in a list

# Create a list
my_list = [10, 25, 5, 40, 15, 2, 30]

# Find largest and smallest elements
largest = max(my_list)
smallest = min(my_list)

# Display the results
print("List:", my_list)
print("Largest element:", largest)
print("Smallest element:", smallest)
