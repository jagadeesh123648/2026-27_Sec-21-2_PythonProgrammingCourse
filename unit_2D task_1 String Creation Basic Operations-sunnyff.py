# String creation
str1 = "Hello"
str2 = "Python"

print("First string:", str1)
print("Second string:", str2)

# 1. Concatenation
result = str1 + " " + str2
print("Concatenation:", result)

# 2. Repetition
print("Repetition:", str1 * 3)

# 3. Slicing
print("Slicing:", str2[0:3])
print("Reverse:", str2[::-1])