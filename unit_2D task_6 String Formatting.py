name = "Jagadeesh"
age = 18
marks = 90

# Using format()
print("Using format():")
print("My name is {} and my age is {}".format(name, age))

# Using f-string
print("\nUsing f-string:")
print(f"My name is {name} and my marks are {marks}")

# Using % operator
print("\nUsing % operator:")
print("My name is %s and my age is %d" % (name, age))